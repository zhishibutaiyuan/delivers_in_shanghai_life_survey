"""生成发给调研组的《采点指南.docx》。

用法：python tools/make_guide.py
输出：docs/采点指南.docx
"""
from common import ROOT, load_taxonomy
from docx_util import GRAY, bullet, new_document, page_numbers, para, rich, steps, table

OUT = ROOT / "docs" / "采点指南.docx"

# 访谈提纲（调研手册附录也用这一份）
INTERVIEW_OPENING = ("您好！我们是复旦大学的学生，在做一张给骑手用的地图，标附近能歇脚的地方和难送的地方。"
                     "耽误您两三分钟，问几个问题可以吗？不记您的名字。")
INTERVIEW_QUESTIONS = [
    "您平时在五角场附近，累了或者等单的时候，一般在哪儿歇一下？",
    "附近有没有能喝水、充电、上厕所的地方？哪家店愿意让骑手进？",
    "知道国和路的新心驿站吗？去过吗？为什么去 / 不去？",
    "附近哪个学校、小区、商场或写字楼最难送？难在哪（进不去、走很远、电梯难等、找不到门）？",
    "哪里停车最麻烦，或者容易被罚？",
    "哪个路口或路段您觉得最危险、最需要慢一点？",
    "如果有这样一张地图，您最想在上面看到什么？",
]


def main():
    tax = load_taxonomy()
    doc = new_document()
    page_numbers(doc)

    doc.add_paragraph("《五角场骑手地图》采点指南", style="Title")
    para(doc, "调研组用 · 技术向善——杨浦区外卖配送调研与信息地图实践 · 2026 秋", color=GRAY, size=10)

    doc.add_heading("一、这次要做什么", level=1)
    rich(doc, ["在五角场一带找到两类地方，记下来交给技术组，标到网页地图上：",
               ("歇脚点", {"bold": True}), "（骑手能休息、喝水、充电、上厕所的地方）和",
               ("障碍点", {"bold": True}), "（送餐容易卡住、绕路、危险的地方）。"])
    bullet(doc, "11 月中旬（期中考试后），具体日期在群里定。", "时间：")
    bullet(doc, "以五角场环岛为中心，沿邯郸路、国定路、政通路、大学路、淞沪路、黄兴路、四平路向外走，步行能到的范围。", "范围：")
    bullet(doc, "每位队员至少交 3 个点；全组访谈约 5 位骑手。", "数量：")
    bullet(doc, "点位采集表、照片、访谈要点、活动照片（见第七节）。", "交什么：")

    doc.add_heading("二、两条底线", level=1)
    steps(doc, [
        ("点位必须真实。", "每个点都必须是你亲自走到、或者骑手当面指给你的地方。分类可以问 AI，"
                         "但点位不能从网上或 AI 那里抄。表里要写清楚来源、采集人、日期。"),
        ("保护骑手隐私。", "不记骑手姓名、手机号；不拍骑手正脸和车牌；骑手原话只写话，不写是谁说的。"),
    ])

    doc.add_heading("三、分类速查", level=1)
    para(doc, "填表时“子类”从下拉框里选。拿不准就选最接近的，在“说明”里写清楚。", color=GRAY, size=10)
    rows = []
    for c in tax["categories"]:
        for s in c["subtypes"]:
            rows.append([c["label"], f'{s["icon"]} {s["label"]}', s["hint"]])
    table(doc, ["大类", "子类", "包括哪些地方"], rows, [2.2, 3.4, 10.4])
    para(doc, "常用标签：" + "、".join(tax["tags"]) + "。也可以自己写新标签。", size=10)

    doc.add_heading("四、到现场怎么记一个点", level=1)
    steps(doc, [
        ("打开网页：", "用手机浏览器打开地图网页，网址后面加 ?pick=1（群里会发链接），就进入坐标拾取模式。"),
        ("取坐标：", "站在点位门口，点“用我的当前位置”。如果定位圈很大或者位置偏了，"
                    "把地图拖到正确位置，直接点一下地图上的那个点。"),
        ("复制坐标：", "点“复制”，到 Excel 里点“经度”那一格粘贴，经度和纬度会自动分到两列。"
                      "现场不方便开 Excel，就先粘贴到微信备忘录里。"),
        ("拍照：", "歇脚点拍入口和里面的设施；障碍点拍禁行标志、门禁、绕行的路、楼宇入口。"
                  "横着拍，一个点 1–2 张就够。不拍人脸和车牌。"),
        ("写说明：", "一两句客观事实，比如“电动车不能进，需从东门步行约 5 分钟到 3 号楼”。"
                    "不写评价性的话（如“保安态度差”）。"),
        ("填表：", "当天回去把点位填进《点位采集表.xlsx》，照片改名后和表格一起交给技术组。"),
    ])

    doc.add_heading("五、骑手访谈怎么问", level=1)
    bullet(doc, "选骑手在店门口等餐、路边休息的时候问；正在赶单、看手机抢单的别打扰。")
    bullet(doc, "每次控制在 3 分钟内；可以准备一瓶水作为感谢。")
    bullet(doc, "请骑手在手机地图上指一下提到的地方，你当场用坐标拾取记下来。")
    bullet(doc, "不录音、不拍骑手正脸；记要点，觉得有代表性的话原样记下来。")
    para(doc, "开场白：", bold=True)
    para(doc, INTERVIEW_OPENING)
    para(doc, "可以问的问题（挑着问，不用全问）：", bold=True)
    steps(doc, INTERVIEW_QUESTIONS)

    doc.add_heading("六、安全", level=1)
    bullet(doc, "出发前由组长统一在腾讯微保购买“短期综合意外险”，截图留存。")
    bullet(doc, "至少两人一组；不在机动车道上停留拍照；过马路走斑马线。")
    bullet(doc, "商场后场、小区内部等需要许可的地方不要硬闯，在门口记录即可。")

    doc.add_heading("七、交付清单", level=1)
    table(doc, ["交什么", "要求"], [
        ["点位采集表.xlsx", "带 * 的列都填上；一行一个点"],
        ["点位照片", "文件名用英文或拼音（如 xinxin-01.jpg），和表里“照片”列一致；原图即可，技术组会处理"],
        ["访谈要点", "每位骑手几句话：说了哪些地方、有代表性的原话；不写姓名"],
        ["活动照片 8 张", "分辨率 1280×960 以上，.jpg，命名为“拍摄者+照片内容简介”"],
        ["保险截图", "每次线下活动的投保截图"],
    ], [4, 12])

    OUT.parent.mkdir(exist_ok=True)
    doc.save(OUT)
    print(f"已生成 {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
